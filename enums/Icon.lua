function Icon.GetDictionary(icon)
    if icon == Icon.MALE or icon == Icon.FEMALE or
       icon == Icon.AUDIO_MUTE or icon == Icon.AUDIO_INACTIVE or
       icon == Icon.AUDIO_VOL1 or icon == Icon.AUDIO_VOL2 or icon == Icon.AUDIO_VOL3 then
        return "mpleaderboard"

    elseif (icon >= Icon.INV_ARM_WRESTLING and icon <= Icon.INV_VEHICLE_DEATHMATCH) then
        return "mpinventory"

    elseif icon == Icon.ADVERSARY or icon == Icon.BASE_JUMPING or icon == Icon.BRIEFCASE or
           icon == Icon.MISSION_STAR or icon == Icon.DEATHMATCH or icon == Icon.CASTLE or
           icon == Icon.TROPHY or icon == Icon.RACE_FLAG or icon == Icon.RACE_FLAG_PLANE or
           icon == Icon.RACE_FLAG_BICYCLE or icon == Icon.RACE_FLAG_PERSON or icon == Icon.RACE_FLAG_CAR or
           icon == Icon.RACE_FLAG_BOAT_ANCHOR or icon == Icon.ROCKSTAR or icon == Icon.STUNT or
           icon == Icon.STUNT_PREMIUM or icon == Icon.RACE_FLAG_STUNT_JUMP or icon == Icon.SHIELD or
           icon == Icon.TEAM_DEATHMATCH or icon == Icon.VEHICLE_DEATHMATCH then
        return "commonmenutu"

    elseif icon == Icon.MP_AMMO_PICKUP or icon == Icon.MP_AMMO or icon == Icon.MP_CASH or
           icon == Icon.MP_RP or icon == Icon.MP_SPECTATING then
        return "mphud"

    elseif icon == Icon.SALE then
        return "mpshopsale"

    elseif icon >= Icon.GLOBE_WHITE and icon <= Icon.GLOBE_ORANGE then
        return "mprankbadge"

    elseif (icon >= Icon.COUNTRY_USA and icon <= Icon.COUNTRY_FRANCE) or
           (icon >= Icon.BRAND_ALBANY and icon <= Icon.BRAND_ZIRCONIUM and
            icon ~= Icon.BRAND_GROTTI2 and icon ~= Icon.BRAND_LCC and
            icon ~= Icon.BRAND_PROGEN2 and icon ~= Icon.BRAND_RUNE) then
        return "mpcarhud"

    elseif icon == Icon.BRAND_GROTTI2 or icon == Icon.BRAND_LCC or
           icon == Icon.BRAND_PROGEN2 or icon == Icon.BRAND_RUNE then
        return "mpcarhud2"

    elseif icon == Icon.INFO then
        return "shared"

    else
        return "commonmenu"
    end
end

