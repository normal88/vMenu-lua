function Icon.GetSize(icon, screenWidth, screenHeight)
    local size30Icons = {
        Icon.CASH, Icon.COKE, Icon.CROWN, Icon.HEROIN, Icon.METH, Icon.WEED,
        Icon.ADVERSARY, Icon.BASE_JUMPING, Icon.BRIEFCASE, Icon.MISSION_STAR,
        Icon.DEATHMATCH, Icon.CASTLE, Icon.TROPHY, Icon.RACE_FLAG, Icon.RACE_FLAG_PLANE,
        Icon.RACE_FLAG_BICYCLE, Icon.RACE_FLAG_PERSON, Icon.RACE_FLAG_CAR, Icon.RACE_FLAG_BOAT_ANCHOR,
        Icon.ROCKSTAR, Icon.STUNT, Icon.STUNT_PREMIUM, Icon.RACE_FLAG_STUNT_JUMP,
        Icon.SHIELD, Icon.TEAM_DEATHMATCH, Icon.VEHICLE_DEATHMATCH,
        Icon.AUDIO_MUTE, Icon.AUDIO_INACTIVE, Icon.AUDIO_VOL1, Icon.AUDIO_VOL2, Icon.AUDIO_VOL3
    }

    for _, v in ipairs(size30Icons) do
        if icon == v then
            return {30 / screenWidth, 30 / screenHeight}
        end
    end

    if (icon >= Icon.COUNTRY_USA and icon <= Icon.COUNTRY_FRANCE) or
       (icon >= Icon.BRAND_ALBANY and icon <= Icon.BRAND_ZIRCONIUM) then
        return {30 / screenWidth, 30 / screenHeight}
    end

    if icon == Icon.STAR or icon == Icon.LOCK_ARENA then
        return {52 / screenWidth, 52 / screenHeight}
    end

    local size22Icons = {
        Icon.MEDAL_SILVER, Icon.MP_AMMO_PICKUP, Icon.MP_AMMO, Icon.MP_CASH, Icon.MP_RP,
        Icon.GLOBE_WHITE, Icon.GLOBE_BLUE, Icon.GLOBE_GREEN, Icon.GLOBE_ORANGE, Icon.GLOBE_RED, Icon.GLOBE_YELLOW
    }

    for _, v in ipairs(size22Icons) do
        if icon == v then
            return {22 / screenWidth, 22 / screenHeight}
        end
    end

    if icon >= Icon.INV_ARM_WRESTLING and icon <= Icon.INV_VEHICLE_DEATHMATCH then
        return {22 / screenWidth, 22 / screenHeight}
    end

    return {38 / screenWidth, 38 / screenHeight}
end

