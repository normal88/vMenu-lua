    if (icon >= Icon.BRAND_ALBANY and icon <= Icon.BRAND_ZIRCONIUM) then
        if selected then
            return enabled and {0, 0, 0} or {50, 50, 50}
        else
            return enabled and {255, 255, 255} or {109, 109, 109}
        end
    end

    if icon == Icon.GLOBE_BLUE then
        return enabled and {10, 103, 166} or {11, 62, 117}
    elseif icon == Icon.GLOBE_GREEN then
        return enabled and {10, 166, 85} or {5, 71, 22}
    elseif icon == Icon.GLOBE_ORANGE then
        return enabled and {232, 145, 14} or {133, 77, 12}
    elseif icon == Icon.GLOBE_RED then
        return enabled and {207, 43, 31} or {110, 7, 7}
    elseif icon == Icon.GLOBE_YELLOW then
        return enabled and {232, 207, 14} or {131, 133, 12}
    end

    return enabled and {255, 255, 255} or {109, 109, 109}
end

return Icon
